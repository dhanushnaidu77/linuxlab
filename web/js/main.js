import { api, connectEvents, store, AuthError } from './api.js';
import { markdown, esc } from './md.js';
import * as T from './term.js';

const $ = (id) => document.getElementById(id);
const ui = {
  state: null,
  channel: store.get('channel', 'platform'),
  threadId: null,
  messages: new Map(), // channel -> Message[]
  lastSeen: store.get('lastSeen', {}), // channel -> last read message id
  view: store.get('view', 'chat'),
  split: store.get('split', false),
  sideTab: 'chat',
  typing: null,
};

// ---------- helpers
const persona = (id) => ui.state?.personas[id];
const time = (ms) => new Date(ms).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
const ago = (ms) => { const m = Math.round((Date.now() - ms) / 60000); return m < 1 ? 'just now' : m < 60 ? `${m}m` : `${Math.floor(m / 60)}h ${m % 60}m`; };
const channelLabel = (c) => (c.startsWith('dm:') ? `@ ${persona(c.slice(3))?.name ?? c.slice(3)}` : `# ${c}`);
const taskById = (id) => ui.state?.openTasks.find((t) => t.id === id) || ui.state?.recentTasks.find((t) => t.id === id);

function toast(msg, ms = 3500) {
  const el = $('toast');
  el.textContent = msg;
  el.classList.remove('hidden');
  clearTimeout(toast.t);
  toast.t = setTimeout(() => el.classList.add('hidden'), ms);
}

async function guarded(fn) {
  try { return await fn(); } catch (e) {
    if (e instanceof AuthError) return showLogin();
    toast(`⚠️ ${e.message}`);
  }
}

// ---------- login
function showLogin() {
  $('app').classList.add('hidden');
  $('login').classList.remove('hidden');
  $('login-pw').focus();
}

$('login-form').addEventListener('submit', async (e) => {
  e.preventDefault();
  $('login-err').textContent = '';
  try {
    await api('/api/login', { password: $('login-pw').value });
    $('login-pw').value = '';
    start();
  } catch (err) { $('login-err').textContent = err.message; }
});

// ---------- state & rendering
async function refreshState() {
  ui.state = await api('/api/state');
  renderHeader();
  renderSidebar();
}

function renderHeader() {
  const s = ui.state;
  const lab = $('lab-status');
  lab.textContent = s.lab.status === 'online' ? '● lab online' : '● lab offline';
  lab.className = `pill ${s.lab.status === 'online' ? 'ok' : 'bad'}`;
  lab.title = Object.entries(s.lab.hosts || {}).map(([h, up]) => `${h}: ${up ? 'up' : 'down'}`).join('\n') || 'unknown';
  const p = $('persona-status');
  p.textContent = s.personaOnline ? '● AI replies' : '● canned replies';
  p.className = `pill ${s.personaOnline ? 'ok' : 'warn'}`;
  p.title = s.personaOnline ? 'Coworker replies generated by Claude' : 'No ANTHROPIC_API_KEY — coworkers use canned replies';
  $('spawn-status').textContent = s.settings.paused ? '⏸ paused' : s.nextSpawnAt ? `next ticket ~${Math.max(0, Math.round((s.nextSpawnAt - Date.now()) / 60000))}m` : '';
  $('streak').textContent = s.streak ? `🔥 ${s.streak}` : '';
  $('level').textContent = `Lvl ${s.level}`;
  const prev = 100 * (s.level - 1) ** 2;
  $('xpfill').style.width = `${Math.min(100, ((s.xp - prev) / (s.nextLevelXp - prev)) * 100)}%`;
  $('xp').textContent = `${s.xp} XP`;
  $('btn-split').classList.toggle('active', ui.split);
}

function unreadCount(channel) {
  const last = ui.state.lastMessageIds[channel] || 0;
  const seen = ui.lastSeen[channel] || 0;
  if (last <= seen) return 0;
  const cached = ui.messages.get(channel);
  return cached ? cached.filter((m) => m.id > seen && m.author !== 'me' && m.kind === 'msg').length || 0 : 1;
}

function renderSidebar() {
  const s = ui.state;
  const chList = $('channel-list');
  chList.innerHTML = '';
  for (const c of s.channels) chList.appendChild(channelItem(c.id, `# ${c.title}`));
  const dms = Object.keys(s.lastMessageIds).filter((c) => c.startsWith('dm:'));
  const dmList = $('dm-list');
  dmList.innerHTML = dms.length ? '' : '<li class="muted small" style="cursor:default">none yet</li>';
  for (const c of dms) dmList.appendChild(channelItem(c, `${persona(c.slice(3))?.avatar ?? '@'} ${persona(c.slice(3))?.name ?? c}`));

  const tl = $('task-list');
  tl.innerHTML = '';
  $('open-count').textContent = s.openTasks.length;
  for (const t of s.openTasks) {
    const li = document.createElement('li');
    li.className = t.id === ui.threadId ? 'active' : '';
    li.innerHTML = `<span class="t-title">${esc(t.title)}</span>
      <span class="t-meta muted"><span class="state ${t.state}">${t.state}</span>${esc(channelLabel(t.channel))} · ⏱ ${ago(t.createdAt)} · ${'★'.repeat(t.difficulty || 1)}</span>`;
    li.onclick = () => openThread(t.id, t.channel);
    tl.appendChild(li);
  }
  if (!s.openTasks.length) tl.innerHTML = '<li class="muted small" style="cursor:default">Nothing open. Enjoy the quiet ☕</li>';

  const sk = $('skill-list');
  sk.innerHTML = '';
  let tier = 0;
  for (const k of s.skills) {
    if (k.tier !== tier) { tier = k.tier; sk.insertAdjacentHTML('beforeend', `<li class="tier">Tier ${tier}</li>`); }
    sk.insertAdjacentHTML('beforeend', `<li class="${k.unlocked ? '' : 'locked'}" title="${k.scenarios} scenarios${k.unlocked ? '' : ' · locked: needs ' + esc(k.requires.join(', ')) + ' ≥ 30'}">
      ${k.unlocked ? '' : '🔒 '}${esc(k.title)} <span class="muted">${k.mastery}</span><div class="bar"><div style="width:${k.mastery}%"></div></div></li>`);
  }

  renderSessions();
  const totalUnread = [...s.channels.map((c) => c.id), ...dms].reduce((n, c) => n + unreadCount(c), 0);
  document.title = totalUnread ? `(${totalUnread}) Darkroom Console` : 'Darkroom Console';
}

function channelItem(id, label) {
  const li = document.createElement('li');
  const n = unreadCount(id);
  li.className = `${id === ui.channel && ui.view !== 'term' ? 'active' : ''} ${n ? 'unread' : ''}`;
  li.innerHTML = `<span>${esc(label)}</span>${n ? `<span class="badge">${n}</span>` : ''}`;
  li.onclick = () => openChannel(id);
  return li;
}

function msgHtml(m, { root = false, replies = 0, task = null } = {}) {
  if (m.kind === 'solution') {
    return `<details class="solution" ${root ? '' : 'open'}><summary>📘 Solution notes</summary><div class="md">${markdown(m.body)}</div></details>`;
  }
  const p = persona(m.author);
  const who = m.author === 'me' ? 'You' : m.author === 'system' ? (m.kind === 'hint' ? '💡 Hint' : 'System') : p?.name ?? m.author;
  const avatar = m.author === 'me' ? '🧑‍💻' : m.author === 'system' ? (m.kind === 'hint' ? '💡' : 'ℹ️') : p?.avatar ?? '👤';
  const body = esc(m.body).replace(/`([^`\n]+)`/g, '<code>$1</code>').replace(/@dhan\b/g, '<span class="mention">@dhan</span>');
  const cls = ['msg', m.author === 'me' && 'me', m.kind === 'hint' && 'hint', m.author === 'system' && m.kind !== 'hint' && 'system', root && 'root'].filter(Boolean).join(' ');
  const link = root && task ? `<div class="thread-link">🧵 ${replies} ${replies === 1 ? 'reply' : 'replies'} <span class="state ${task.state}">${task.state}</span></div>` : '';
  return `<div class="${cls}" ${root ? `data-task="${m.taskId}"` : ''}>
    <div class="avatar">${avatar}</div>
    <div><div><span class="who">${esc(who)}</span>${p && m.author !== 'me' ? `<span class="role">${esc(p.role)}</span>` : ''}<span class="when">${time(m.at)}</span></div>
    <div class="body">${body}</div>${link}</div></div>`;
}

async function loadChannel(ch) {
  if (!ui.messages.has(ch)) ui.messages.set(ch, await api(`/api/messages?channel=${encodeURIComponent(ch)}`));
  return ui.messages.get(ch);
}

async function openChannel(ch) {
  ui.channel = ch;
  store.set('channel', ch);
  if (!ui.split) setView('chat');
  await guarded(renderChannel);
  renderSidebar();
}

async function renderChannel() {
  const ch = ui.channel;
  const msgs = await loadChannel(ch);
  const meta = ui.state.channels.find((c) => c.id === ch);
  $('channel-title').textContent = channelLabel(ch);
  $('channel-topic').textContent = meta?.topic ?? (ch.startsWith('dm:') ? persona(ch.slice(3))?.role ?? '' : '');
  // channel shows the root (first) message of each task plus non-task messages
  // reply count = chat messages in the thread after the root
  const replies = {};
  for (const m of msgs) if (m.taskId != null && m.kind === 'msg') replies[m.taskId] = (replies[m.taskId] ?? -1) + 1;
  const seenTasks = new Set();
  const html = [];
  for (const m of msgs) {
    if (m.taskId == null) { html.push(msgHtml(m)); continue; }
    if (seenTasks.has(m.taskId)) continue;
    seenTasks.add(m.taskId);
    html.push(msgHtml(m, { root: true, replies: replies[m.taskId], task: taskById(m.taskId) || { state: 'closed' } }));
  }
  const box = $('channel-msgs');
  box.innerHTML = html.join('') || '<div class="empty muted">No messages yet.</div>';
  box.querySelectorAll('.msg.root').forEach((el) => (el.onclick = () => openThread(Number(el.dataset.task), ch)));
  box.scrollTop = box.scrollHeight;
  if (msgs.length) { ui.lastSeen[ch] = msgs.at(-1).id; store.set('lastSeen', ui.lastSeen); }
}

async function openThread(taskId, channel) {
  if (channel && channel !== ui.channel) { ui.channel = channel; store.set('channel', channel); await guarded(renderChannel); }
  ui.threadId = taskId;
  if (!ui.split) setView('chat');
  $('thread').classList.remove('hidden');
  $('chat-view').classList.add('has-thread');
  await guarded(renderThread);
  renderSidebar();
  $('composer-text').focus();
}

async function renderThread() {
  if (ui.threadId == null) return;
  const msgs = (await loadChannel(ui.channel)).filter((m) => m.taskId === ui.threadId);
  const t = taskById(ui.threadId);
  $('thread-title').textContent = t?.title ?? 'Thread';
  $('thread-meta').innerHTML = t ? `<span class="state ${t.state}">${t.state}</span> ${'★'.repeat(t.difficulty || 1)} · ${esc(t.skills.join(', '))} · opened ${ago(t.createdAt)} ago${t.hintsUsed ? ` · ${t.hintsUsed} hint${t.hintsUsed > 1 ? 's' : ''}` : ''}` : '';
  const box = $('thread-msgs');
  box.innerHTML = msgs.map((m) => msgHtml(m)).join('');
  box.scrollTop = box.scrollHeight;
  const open = t && (t.state === 'open' || t.state === 'checking');
  $('composer').classList.toggle('hidden', !open);
  $('btn-hint').disabled = !open || t.hintsLeft <= 0;
  $('btn-hint').textContent = `💡 Hint${t && open ? ` (${t.hintsLeft} left)` : ''}`;
  $('typing').classList.toggle('hidden', !(ui.typing && ui.typing.taskId === ui.threadId));
  if (ui.typing && ui.typing.taskId === ui.threadId) $('typing').textContent = `${persona(ui.typing.persona)?.name ?? 'someone'} is typing…`;
}

$('thread-close').onclick = () => { ui.threadId = null; $('thread').classList.add('hidden'); $('chat-view').classList.remove('has-thread'); renderSidebar(); };

$('composer').addEventListener('submit', async (e) => {
  e.preventDefault();
  const text = $('composer-text').value.trim();
  if (!text || ui.threadId == null) return;
  $('composer-text').value = '';
  const id = ui.threadId;
  await guarded(async () => {
    const r = await api(`/api/tasks/${id}/reply`, { text });
    if (r.error) toast(r.error);
    if (r.pass) toast(`✅ Ticket solved! +${r.xp} XP`);
  });
});
$('composer-text').addEventListener('keydown', (e) => {
  if (e.key === 'Enter' && !e.shiftKey) { e.preventDefault(); $('composer').requestSubmit(); }
});
$('btn-hint').onclick = () => guarded(() => api(`/api/tasks/${ui.threadId}/hint`, {}));
$('btn-skip').onclick = () => {
  if (confirm('Skip this ticket? You get no XP, a small mastery penalty, and the solution is shown.')) guarded(() => api(`/api/tasks/${ui.threadId}/skip`, {}));
};

// ---------- view switching
function setView(v) {
  ui.view = v;
  store.set('view', v);
  const main = $('main');
  main.classList.toggle('split', ui.split);
  main.classList.toggle('view-chat', !ui.split && v === 'chat');
  main.classList.toggle('view-term', !ui.split && v === 'term');
  setSideTab(v);
  if (v === 'term' || ui.split) {
    if (!T.count()) T.newSession();
    T.fitActive();
    if (v === 'term') T.focusActive();
  }
  renderTermEmpty();
}

function setSideTab(tab) {
  ui.sideTab = tab;
  document.querySelectorAll('.tab').forEach((b) => b.classList.toggle('active', b.dataset.tab === tab));
  $('side-chat').classList.toggle('hidden', tab !== 'chat');
  $('side-term').classList.toggle('hidden', tab !== 'term');
}

document.querySelectorAll('.tab').forEach((b) => (b.onclick = () => (ui.split ? setSideTab(b.dataset.tab) : setView(b.dataset.tab))));

function toggleSplit() {
  ui.split = !ui.split;
  store.set('split', ui.split);
  setView(ui.view);
  renderHeader();
}
$('btn-split').onclick = toggleSplit;
// capture phase so the shortcut works even while xterm has focus
document.addEventListener('keydown', (e) => {
  if (e.ctrlKey && e.key === '\\') { e.preventDefault(); e.stopPropagation(); toggleSplit(); }
}, true);

// ---------- terminal sessions
function renderSessions() {
  const ul = $('session-list');
  ul.innerHTML = '';
  for (const s of T.list()) {
    const li = document.createElement('li');
    li.className = s.active ? 'active' : '';
    li.innerHTML = `<span>${s.alive ? '🟢' : '⚪'} ${esc(s.name)}</span><span class="x" title="Close">✕</span>`;
    li.onclick = (e) => {
      if (e.target.classList.contains('x')) return T.close(s.id);
      if (!ui.split) setView('term');
      T.activate(s.id);
    };
    li.ondblclick = () => T.rename(s.id, prompt('Session name', s.name));
    ul.appendChild(li);
  }
  renderTermEmpty();
}
const renderTermEmpty = () => $('term-empty').classList.toggle('hidden', T.count() > 0);
const newSession = () => { if (!ui.split) setView('term'); T.newSession(); };
$('btn-new-session').onclick = newSession;
$('btn-new-session-2').onclick = newSession;

