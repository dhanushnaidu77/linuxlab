// ---------- live events
function onEvent(e) {
  if (e.type === 'message') {
    const m = e.message;
    const arr = ui.messages.get(m.channel);
    if (arr && !arr.some((x) => x.id === m.id)) arr.push(m);
    if (ui.state) ui.state.lastMessageIds[m.channel] = m.id;
    if (ui.typing?.taskId === m.taskId && m.author !== 'me') ui.typing = null;
    if (m.channel === ui.channel) renderChannel();
    if (m.taskId === ui.threadId) renderThread();
    renderSidebar();
    if (m.author !== 'me' && m.kind === 'msg' && document.hidden) notify(m);
  } else if (e.type === 'task' && ui.state) {
    const t = e.task;
    ui.state.openTasks = ui.state.openTasks.filter((x) => x.id !== t.id);
    ui.state.recentTasks = ui.state.recentTasks.filter((x) => x.id !== t.id);
    (['open', 'checking'].includes(t.state) ? ui.state.openTasks : ui.state.recentTasks).unshift(t);
    ui.state.openTasks.sort((a, b) => a.id - b.id);
    if (t.id === ui.threadId) renderThread();
    renderSidebar();
    if (ui.channel === t.channel) renderChannel();
  } else if (e.type === 'typing') {
    ui.typing = e;
    if (e.taskId === ui.threadId) renderThread();
    setTimeout(() => { if (ui.typing === e) { ui.typing = null; renderThread(); } }, 20000);
  } else if (e.type === 'reset') {
    location.reload();
  } else if (e.type === 'progress' || e.type === 'lab') {
    guarded(refreshState);
  }
}

function notify(m) {
  if (!('Notification' in window) || Notification.permission !== 'granted') return;
  const p = persona(m.author);
  new Notification(`${p?.name ?? m.author} · ${channelLabel(m.channel)}`, { body: m.body.slice(0, 140) });
}

// ---------- boot
async function start() {
  try { await refreshState(); } catch (e) { if (e instanceof AuthError) return showLogin(); throw e; }
  $('login').classList.add('hidden');
  $('app').classList.remove('hidden');
  T.initTerminals(renderSessions);
  if (!ui.state.channels.some((c) => c.id === ui.channel) && !ui.channel.startsWith('dm:')) ui.channel = 'platform';
  setView(ui.view);
  await renderChannel();
  connectEvents(onEvent, (up) => { if (up) refreshState().catch(() => {}); });
  setInterval(() => ui.state && (renderHeader(), renderSidebar()), 30000);
  if ('Notification' in window && Notification.permission === 'default') document.addEventListener('click', () => Notification.requestPermission(), { once: true });
}

start();
