async function labAction(path, body, label) {
  $('lab-msg').textContent = `${label}… (this can take a minute)`;
  await guarded(async () => {
    const r = await api(path, body);
    $('lab-msg').textContent = r.ok ? `${label} done ✔` : `${label} failed: ${r.error}`;
    ui.messages.clear();
    await refreshState();
    await renderChannel();
    renderThread();
  });
}
